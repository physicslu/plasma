#!/usr/bin/env python3
"""Generate reproducible, uniformly distributed diagnostic Flash bytes.

Not cryptographic key material. The generated C is a build byproduct, not
checked-in giant random data; the linker explicitly KEEP()s the section.
"""
import argparse
import hashlib
from pathlib import Path
import struct

DEFAULT_SEED = 0x504C4153
DEFAULT_SIZE = 44032


def payload_bytes(size=DEFAULT_SIZE, seed=DEFAULT_SEED):
    if not 0 < size <= 65536 or not 0 <= seed <= 0xFFFFFFFF:
        raise ValueError("invalid size or seed")
    result = bytearray()
    counter = 0
    while len(result) < size:
        result.extend(hashlib.sha256(struct.pack("<II", seed, counter)).digest())
        counter += 1
    return bytes(result[:size])


def c_source(data):
    lines = [
        "/* Generated by host/generate_flash_payload.py; DO NOT EDIT. */",
        "#include <stdint.h>",
        "/* Kept in program Flash, not copied into .data/.bss or accessed at runtime. */",
        '__attribute__((used, aligned(4), section(".flash_test_payload")))',
        "const uint8_t plasma_blue_pill_flash_test_payload[] = {",
    ]
    for offset in range(0, len(data), 16):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[offset:offset + 16]) + ",")
    lines.extend(["};", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("destination", type=Path)
    parser.add_argument("--size", type=int, default=DEFAULT_SIZE)
    parser.add_argument("--seed", type=lambda x: int(x, 0), default=DEFAULT_SEED)
    args = parser.parse_args()
    data = payload_bytes(args.size, args.seed)
    args.destination.parent.mkdir(parents=True, exist_ok=True)
    source = c_source(data)
    args.destination.write_text(source, encoding="ascii")
    print(f"FLASH_TEST_PAYLOAD size={len(data)} sha256={hashlib.sha256(data).hexdigest()}")


if __name__ == "__main__":
    main()
