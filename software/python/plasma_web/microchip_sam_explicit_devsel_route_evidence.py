def admitted_sam_explicit_devsel_routes(
    catalog: DeviceCatalog,
) -> AdmittedRouteCandidateRegistry:
    """Expose separately admitted exact manufacturer identities as L1 only."""
    admitted_microchip_phase1_count(catalog)
    rows = [row for row in catalog.records
            if row.vendor == "Microchip" and row.family in SAM_PHASE2_COHORTS]
    if not rows:
        return AdmittedRouteCandidateRegistry(catalog, ())
    if (len(rows) != 892 or len(SAM_EXPLICIT_DEVSEL) != 84
            or {row.base_device for row in rows} != set(SAM_EXPLICIT_DEVSEL)):
        raise DeviceCatalogIntegrityError("Microchip 892 SAM Phase-2 DEVSEL membership drift")
    evidences = []
    for row in rows:
        base = row.base_device or ""
        entry = SAM_EXPLICIT_DEVSEL.get(base)
        if entry is None:
            raise DeviceCatalogIntegrityError("Unknown Microchip SAM Base Device " + base)
        family, devsel = entry
        driver = SAM_PHASE2_COHORTS[family]
        ref = row.source_reference or ""
        prefix = "original_response_sha256="
        if (family != row.family or prefix not in ref
                or f"basePartNumber={base}" not in ref
                or f"partNumber={row.identifier}" not in ref
                or f"original_replay_index_git_blob={SAM_PHASE2_ORIGINAL_BLOB}" not in ref
                or f"driver_path={driver[2]}" not in ref
                or f"driver_blob={driver[3]}" not in ref
                or f"driver_devsel={devsel}" not in ref):
            raise DeviceCatalogIntegrityError(
                "Microchip SAM Phase-2 exact Device ID/source mismatch " + row.identifier
            )
        digest = ref.split(prefix, 1)[1][:64]
        evidences.append(RouteEvidence(
            manufacturer="Microchip",
            exact_icpn=row.identifier,
            base_device=base,
            identity_source=SOURCE_MCP_URI,
            identity_sha256=digest,
            base_device_source=ref,
            provider_id="openocd-upstream-sam-explicit-part-candidate",
            provider_version="0.12.0",
            provider_source_commit=PIC32_PINNED_COMMIT,
            route_kind="DRIVER",
            route_source_path=driver[2],
            route_source_blob=driver[3],
            applicability_source=(
                f"OpenOCD v0.12.0 pinned {driver[2]} "
                f"part table exact entry {base[2:]} DEVSEL={devsel}; "
                f"locked blob {driver[3]}; manufacturer basePartNumber={base}"
            ),
            applicability="VERIFIED_BASE_DEVICE",
        ))
    return AdmittedRouteCandidateRegistry(catalog, tuple(evidences))
