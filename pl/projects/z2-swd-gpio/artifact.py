#!/usr/bin/env python3
"""Generate identity constants and immutable Z2 PoC FPGA artifact metadata.

This is a HOST-side build tool. It never loads/configures an FPGA.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import shutil
import subprocess
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
VERSION = re.compile(r"^(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)$")
SHA = re.compile(r"^[0-9a-f]{40}$")


def _commit() -> str:
    result = subprocess.check_output(
        ["git", "-C", str(REPO), "rev-parse", "HEAD"], text=True
    ).strip()
    if not SHA.fullmatch(result):
        raise ValueError("Git HEAD must be a full SHA-1 commit")
    # Never claim that a dirty worktree represents only the reported commit.
    dirty = subprocess.check_output(
        ["git", "-C", str(REPO), "status", "--porcelain", "--untracked-files=no"],
        text=True,
    )
    if dirty.strip():
        raise ValueError("Source checkout has modified tracked files; commit changes before release build")
    return result


def _version(value: str) -> tuple[int, int, int]:
    match = VERSION.fullmatch(value)
    if not match:
        raise ValueError("Bitstream version must be MAJOR.MINOR.PATCH (no prerelease in ABI v1)")
    parts = tuple(map(int, match.groups()))
    if any(part > 255 for part in parts):
        raise ValueError("ABI v1 register encodes each SemVer component in 8 bits")
    return parts  # type: ignore[return-value]


def prepare(output: Path, version: str) -> None:
    major, minor, patch = _version(version)
    commit = _commit()
    output.mkdir(parents=True, exist_ok=True)
    build_id = commit[:32]
    encoded = (major << 16) | (minor << 8) | patch
    header = (
        "// AUTOGENERATED — do not edit; build-only, not source-of-truth.\n"
        f"localparam logic [31:0] PLSM_VERSION = 32'h{encoded:08X};\n"
    )
    for i in range(4):
        word = build_id[i * 8 : (i + 1) * 8]
        header += f"localparam logic [31:0] PLSM_BUILD_ID_{i} = 32'h{word.upper()};\n"
    (output / "plasma_identity_generated.vh").write_text(header)
    identity = {
        "identity_schema_version": 1,
        "bitstream_version": version,
        "hardware_abi_version": 1,
        "source_git_sha": commit,
        "build_id": build_id,
        "target_board": "pynq-z2",
        "target_board_revision": "not-yet-qualified",
        "fpga_part": "xc7z020clg400-1",
        "capabilities": ["swd_gpio"],
        "capability_flags": 1,
        "hardware_runtime_ready": False,
        "physical_programming_qualified": False,
    }
    (output / "build-identity.json").write_text(
        json.dumps(identity, indent=2, sort_keys=True) + "\n"
    )
    print(f"IDENTITY_PREPARED commit={commit} version={version}")


def _digest(path: Path) -> str:
    sha = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            sha.update(chunk)
    return sha.hexdigest()


def finalize(output: Path, project: Path, vivado_version: str, address_file: Path) -> None:
    identity = json.loads((output / "build-identity.json").read_text())
    if identity["source_git_sha"] != _commit():
        raise ValueError("Source commit changed after identity preparation")
    bit_candidates = list((project / "z2_swd_gpio.runs" / "impl_1").glob("system_wrapper.bit"))
    if len(bit_candidates) != 1:
        raise ValueError(f"Expected one implemented system_wrapper.bit, found {len(bit_candidates)}")
    hwh_candidates = list((project / "z2_swd_gpio.gen").glob("sources_1/bd/system/hw_handoff/system.hwh"))
    if len(hwh_candidates) != 1:
        raise ValueError(f"Expected one Vivado hardware-handoff system.hwh, found {len(hwh_candidates)}")
    addr = address_file.read_text().strip()
    if not re.fullmatch(r"0[xX][0-9a-fA-F]{8}", addr):
        raise ValueError(f"Invalid AXI identity base address: {addr!r}")

    artifacts = output.parent / "artifacts"
    artifacts.mkdir(parents=True, exist_ok=True)
    stem = f"plasma-z2-swd-gpio-{identity['bitstream_version']}"
    bit = artifacts / f"{stem}.bit"
    hwh = artifacts / f"{stem}.hwh"
    shutil.copyfile(bit_candidates[0], bit)
    shutil.copyfile(hwh_candidates[0], hwh)
    identity.update(
        bitstream_file=bit.name,
        bitstream_sha256=_digest(bit),
        hwh_file=hwh.name,
        hwh_sha256=_digest(hwh),
        identity_axi_base_address=addr.upper().replace("0X", "0x"),
        identity_register_span=32,
        toolchain={"name": "Vivado", "version": vivado_version},
        build_validation={
            "synthesis": "PASS",
            "implementation": "PASS",
            "timing_checks": "PASS",
            "physical_hil": "NOT_RUN",
        },
    )
    manifest = artifacts / "manifest.json"
    manifest.write_text(json.dumps(identity, indent=2, sort_keys=True) + "\n")
    (artifacts / f"{bit.name}.sha256").write_text(f"{identity['bitstream_sha256']}  {bit.name}\n")
    (artifacts / f"{hwh.name}.sha256").write_text(f"{identity['hwh_sha256']}  {hwh.name}\n")
    print(f"ARTIFACT_PASS {bit}")
    print(f"MANIFEST {manifest}")
    print(f"IDENTITY_AXI_BASE {addr}")


def main() -> int:
    parser = argparse.ArgumentParser()
    sub = parser.add_subparsers(dest="command", required=True)
    p = sub.add_parser("prepare")
    p.add_argument("--output", type=Path, required=True)
    p.add_argument("--version", default="0.1.0")
    p = sub.add_parser("finalize")
    p.add_argument("--output", type=Path, required=True)
    p.add_argument("--project", type=Path, required=True)
    p.add_argument("--vivado-version", required=True)
    p.add_argument("--identity-address-file", type=Path, required=True)
    args = parser.parse_args()
    try:
        if args.command == "prepare":
            prepare(args.output.resolve(), args.version)
        else:
            finalize(args.output.resolve(), args.project.resolve(),
                     args.vivado_version, args.identity_address_file.resolve())
    except (ValueError, OSError, subprocess.SubprocessError, KeyError) as exc:
        parser.exit(2, f"ERROR: {exc}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
